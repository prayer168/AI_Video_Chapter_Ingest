#!/usr/bin/env python3
"""Create and update safe, resumable chapter pipeline checkpoints."""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import uuid
from datetime import datetime
from pathlib import Path
from typing import Any

try:
    import yaml
except ImportError:
    yaml = None

ROOT = Path(__file__).resolve().parents[1]
STEP_IDS = (
    "inventory", "research", "zh-draft", "en-translation", "film-cases",
    "figure-assets", "svg-diagrams", "website", "books", "tests",
    "editorial-review", "rights-review", "author-approval",
)
STEP_STATUSES = {"pass", "fail", "blocked", "needs-human-review", "not-run"}


def read_yaml(path: Path) -> Any:
    if yaml is None:
        raise RuntimeError("PyYAML is required. Install requirements-v2.txt first.")
    if not path.exists():
        return None
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def chapter_record(root: Path, number: int) -> dict[str, Any]:
    if not 1 <= number <= 60:
        raise ValueError("chapter must be between 1 and 60")
    registry = read_yaml(root / "metadata" / "chapters.yaml") or []
    rows = registry if isinstance(registry, list) else registry.get("chapters", [])
    chapter_id = f"CH{number:02d}"
    matches = [row for row in rows if row.get("chapter_id") == chapter_id]
    if len(matches) != 1:
        raise ValueError(f"Expected exactly one registry record for {chapter_id}; found {len(matches)}")
    return matches[0]


def discover_files(root: Path, record: dict[str, Any]) -> list[dict[str, Any]]:
    chapter_id = record["chapter_id"]
    found: list[Path] = []
    for locale in ("zh-TW", "en-US"):
        folder = root / "content" / locale / "chapters"
        found.extend(sorted(folder.glob(f"{chapter_id}-*.md")) if folder.exists() else [])
    manifest = root / "assets" / "chapters" / chapter_id / "figure-manifest.yaml"
    alignment = root / "metadata" / "translations" / f"{chapter_id}-alignment.yaml"
    for path in (manifest, alignment):
        if path.exists():
            found.append(path)
    result = []
    for path in found:
        data = path.read_bytes()
        result.append({
            "path": path.relative_to(root).as_posix(),
            "bytes": len(data),
            "sha256": hashlib.sha256(data).hexdigest(),
        })
    return result


def current_status(root: Path, chapter_id: str) -> dict[str, Any]:
    statuses = read_yaml(root / "metadata" / "translation-status.yaml") or {}
    row = (statuses.get("chapters") or {}).get(chapter_id, {})
    return row if isinstance(row, dict) else {}


def render_checklist(run: dict[str, Any]) -> str:
    lines = [
        f"# {run['chapter_id']} Pipeline Run",
        "",
        f"- Run ID: `{run['run_id']}`",
        f"- Created: {run['created_at']}",
        f"- Status: `{run['status']}`",
        "- Mode: inspect/checkpoint only at initialization; no manuscript or media is generated by this runner.",
        "",
        "## Existing progress",
        "",
        f"- Registry title (zh): {run['chapter'].get('title_zh', '')}",
        f"- Registry title (en): {run['chapter'].get('title_en', '')}",
        f"- Translation status: `{json.dumps(run['translation_status'], ensure_ascii=False)}`",
        "- Existing files:",
    ]
    lines.extend(f"  - `{item['path']}` — {item['bytes']} bytes; SHA-256 `{item['sha256']}`" for item in run["existing_files"])
    if not run["existing_files"]:
        lines.append("  - None found")
    lines += ["", "## Stages", "", "| Stage | Status | Notes |", "|---|---|---|"]
    lines.extend(f"| `{key}` | `{value['status']}` | {value.get('note', '')} |" for key, value in run["steps"].items())
    lines += ["", "## Run events", ""]
    lines.extend(f"- {event['time']} — {event['event']}" for event in run["events"])
    lines.append("")
    return "\n".join(lines)


def write_run_files(run_dir: Path, run: dict[str, Any]) -> None:
    (run_dir / "run.json").write_text(json.dumps(run, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (run_dir / "CHECKLIST.md").write_text(render_checklist(run), encoding="utf-8")


def start_run(root: Path, number: int) -> Path:
    record = chapter_record(root, number)
    chapter_id = record["chapter_id"]
    now = datetime.now().astimezone()
    run_id = now.strftime("%Y%m%dT%H%M%S%z") + "-" + uuid.uuid4().hex[:8]
    run_dir = root / "production" / "runs" / chapter_id / run_id
    run_dir.mkdir(parents=True, exist_ok=False)
    run = {
        "schema_version": 1,
        "run_id": run_id,
        "chapter_id": chapter_id,
        "created_at": now.isoformat(),
        "status": "in-progress",
        "chapter": record,
        "translation_status": current_status(root, chapter_id),
        "existing_files": discover_files(root, record),
        "steps": {key: {"status": "not-run", "note": ""} for key in STEP_IDS},
        "events": [{"time": now.isoformat(), "event": "Checkpoint created. No manuscripts, images, or publication outputs changed."}],
    }
    write_run_files(run_dir, run)
    return run_dir


def safe_run_dir(root: Path, number: int, value: str | Path) -> Path:
    expected = (root / "production" / "runs" / f"CH{number:02d}").resolve()
    path = Path(value)
    resolved = (root / path).resolve() if not path.is_absolute() else path.resolve()
    if expected not in resolved.parents or not resolved.is_dir():
        raise ValueError("run-dir must be an existing folder under production/runs/CHNN/")
    if not (resolved / "run.json").is_file():
        raise ValueError("run-dir has no run.json checkpoint")
    return resolved


def update_run(root: Path, number: int, run_path: str | Path, step: str | None = None, note: str = "", finish: str | None = None) -> Path:
    run_dir = safe_run_dir(root, number, run_path)
    data_path = run_dir / "run.json"
    run = json.loads(data_path.read_text(encoding="utf-8"))
    now = datetime.now().astimezone().isoformat()
    if step:
        if "=" not in step:
            raise ValueError("step must be STAGE=STATUS")
        stage, status = step.split("=", 1)
        if stage not in run["steps"]:
            raise ValueError(f"Unknown stage: {stage}")
        if status not in STEP_STATUSES:
            raise ValueError(f"Unknown status: {status}")
        run["steps"][stage] = {"status": status, "note": note}
        run["events"].append({"time": now, "event": f"Stage {stage} recorded as {status}.", "note": note})
    if finish:
        if finish == "complete":
            pending = [key for key, value in run["steps"].items() if value["status"] != "pass"]
            if pending:
                raise ValueError("Cannot mark complete; stages are not PASS: " + ", ".join(pending))
        run["status"] = finish
        run["finished_at"] = now
        run["events"].append({"time": now, "event": f"Run finished as {finish}.", "note": note})
    write_run_files(run_dir, run)
    return run_dir


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--chapter", type=int, required=True, help="chapter number 1–60")
    parser.add_argument("--run-dir", help="existing run folder for recording a stage or finish status")
    parser.add_argument("--step", help="record STAGE=pass|fail|blocked|needs-human-review|not-run")
    parser.add_argument("--note", default="", help="short evidence or blocker note")
    parser.add_argument("--finish", choices=("complete", "partial", "blocked"))
    args = parser.parse_args(argv)
    try:
        if args.step or args.finish:
            if not args.run_dir:
                raise ValueError("--run-dir is required with --step or --finish")
            path = update_run(ROOT, args.chapter, args.run_dir, args.step, args.note, args.finish)
        else:
            if args.run_dir:
                raise ValueError("--run-dir alone is not an action; pass --step or --finish")
            path = start_run(ROOT, args.chapter)
        print(path.relative_to(ROOT).as_posix())
        return 0
    except (OSError, ValueError, RuntimeError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
